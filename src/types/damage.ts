// damageType.ts - 伤害类型数据结构

// ============================================================
// 伤害类型定义
// ============================================================

/**
 * 伤害类型配置
 */
export interface DamageType {
  /** 伤害类型唯一ID */
  id: string
  /** 伤害类型名称（显示用） */
  name: string
  /** 伤害类型描述 */
  description: string
  /** 伤害类型图标资源ID */
  iconId: string
  /** 伤害类型对应文字颜色（用于战斗日志中显示伤害数值） */
  textColor: string
  // 无视防御系数（1为无视防御，0为不无视防御，中间值为部分无视）
  defensePenetration: number
}

// ============================================================
// 伤害类型ID
// ============================================================

/**
 * 伤害类型ID（伤害与防御统一使用）
 * 防御属性以伤害类型ID为键存储（与 damageTypes.ts 注册表一致），
 * 新增伤害类型时在此补充即可，无需改动战斗引擎
 */
export type DamageTypeId =
  | 'slash'
  | 'pierce'
  | 'blunt'
  | 'ranged'
  | 'poison'
  | 'fire'
  | 'realDamage'

// ============================================================
// 伤害类型注册表
// ============================================================

/**
 * 伤害类型注册表
 */
export interface DamageTypeRegistry {
  damageTypes: Record<string, DamageType>
}
